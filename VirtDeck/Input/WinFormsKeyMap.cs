namespace VirtDeck.Input
{
    /// <summary>
    /// Maps Windows virtual-key codes to the SPICE wire scancode (PC/AT set 1).
    /// Extended ("grey") keys are encoded as 0xE0 | (atCode &lt;&lt; 8), matching
    /// spice-html5 utils.js — NOT the 0xE0XX form. KEY_UP applies the high bit in
    /// InputsChannel.SendKey.
    /// </summary>
    public static class WinFormsKeyMap
    {
        // Helper for extended keys: prefix 0xE0 in the low byte, AT code in the high byte.
        private static uint Ext(uint at) => 0xE0u | (at << 8);

        private static readonly Dictionary<int, uint> Map = new()
        {
            // Control keys
            [0x08] = 0x0E, // Backspace
            [0x09] = 0x0F, // Tab
            [0x0D] = 0x1C, // Enter
            [0x13] = 0x45, // Pause
            [0x14] = 0x3A, // CapsLock
            [0x1B] = 0x01, // Escape
            [0x20] = 0x39, // Space

            // Navigation (extended)
            [0x21] = Ext(0x49), // PageUp
            [0x22] = Ext(0x51), // PageDown
            [0x23] = Ext(0x4F), // End
            [0x24] = Ext(0x47), // Home
            [0x25] = Ext(0x4B), // Left
            [0x26] = Ext(0x48), // Up
            [0x27] = Ext(0x4D), // Right
            [0x28] = Ext(0x50), // Down
            [0x2C] = Ext(0x37), // PrintScreen
            [0x2D] = Ext(0x52), // Insert
            [0x2E] = Ext(0x53), // Delete

            // Number row 0-9
            [0x30] = 0x0B, [0x31] = 0x02, [0x32] = 0x03, [0x33] = 0x04,
            [0x34] = 0x05, [0x35] = 0x06, [0x36] = 0x07, [0x37] = 0x08,
            [0x38] = 0x09, [0x39] = 0x0A,

            // A-Z
            [0x41] = 0x1E, [0x42] = 0x30, [0x43] = 0x2E, [0x44] = 0x20,
            [0x45] = 0x12, [0x46] = 0x21, [0x47] = 0x22, [0x48] = 0x23,
            [0x49] = 0x17, [0x4A] = 0x24, [0x4B] = 0x25, [0x4C] = 0x26,
            [0x4D] = 0x32, [0x4E] = 0x31, [0x4F] = 0x18, [0x50] = 0x19,
            [0x51] = 0x10, [0x52] = 0x13, [0x53] = 0x1F, [0x54] = 0x14,
            [0x55] = 0x16, [0x56] = 0x2F, [0x57] = 0x11, [0x58] = 0x2D,
            [0x59] = 0x15, [0x5A] = 0x2C,

            // Windows / Menu keys (extended)
            [0x5B] = Ext(0x5B), // LWin
            [0x5C] = Ext(0x5C), // RWin
            [0x5D] = Ext(0x5D), // Apps/Menu

            // Numpad (NumLock on)
            [0x60] = 0x52, [0x61] = 0x4F, [0x62] = 0x50, [0x63] = 0x51,
            [0x64] = 0x4B, [0x65] = 0x4C, [0x66] = 0x4D, [0x67] = 0x47,
            [0x68] = 0x48, [0x69] = 0x49,
            [0x6A] = 0x37,      // Multiply
            [0x6B] = 0x4E,      // Add
            [0x6D] = 0x4A,      // Subtract
            [0x6E] = 0x53,      // Decimal
            [0x6F] = Ext(0x35), // Divide (extended)

            // F1-F12
            [0x70] = 0x3B, [0x71] = 0x3C, [0x72] = 0x3D, [0x73] = 0x3E,
            [0x74] = 0x3F, [0x75] = 0x40, [0x76] = 0x41, [0x77] = 0x42,
            [0x78] = 0x43, [0x79] = 0x44, [0x7A] = 0x57, [0x7B] = 0x58,

            // Modifiers / locks
            [0x90] = 0x45,      // NumLock
            [0x91] = 0x46,      // ScrollLock
            [0xA0] = 0x2A,      // LShift
            [0xA1] = 0x36,      // RShift
            [0xA2] = 0x1D,      // LCtrl
            [0xA3] = Ext(0x1D), // RCtrl (extended)
            [0xA4] = 0x38,      // LAlt
            [0xA5] = Ext(0x38), // RAlt (extended)

            // OEM
            [0xBA] = 0x27, // ;:
            [0xBB] = 0x0D, // =+
            [0xBC] = 0x33, // ,<
            [0xBD] = 0x0C, // -_
            [0xBE] = 0x34, // .>
            [0xBF] = 0x35, // /?
            [0xC0] = 0x29, // `~
            [0xDB] = 0x1A, // [{
            [0xDC] = 0x2B, // \|
            [0xDD] = 0x1B, // ]}
            [0xDE] = 0x28, // '"
        };

        public static bool TryMap(int vkCode, out uint scancode) => Map.TryGetValue(vkCode, out scancode);
    }
}
